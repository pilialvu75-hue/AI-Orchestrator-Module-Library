"""Create a non-admitted TESTED intake artifact from verified async consumer evidence."""
import argparse
import copy
import json
import os
from pathlib import Path
import shutil
from datetime import datetime, timezone

from library_source_integrity import payload_tree_sha256
from verify_next_async_admission import verify


def materialize(root, candidate, upstream, consumer, adapter, delivery, bundle, output):
    verified = verify(upstream, consumer, adapter)
    if candidate.get("package") != "async" or candidate.get("source_commit") != verified["source_commit"]:
        raise ValueError("candidate source identity mismatch")
    if (delivery.get("package") != "async"
            or delivery.get("source_commit") != verified["source_commit"]
            or delivery.get("delivery_integrity") != "MATCH"
            or delivery.get("separate_consumer") != "BEHAVIOR_PASS"
            or delivery.get("bundle_sha256") != delivery.get("original_bundle_sha256")
            or delivery.get("admission_authorized") is not False
            or delivery.get("certification_authorized") is not False):
        raise ValueError("delivered source evidence missing or mismatched")
    if output.exists():
        raise ValueError("output must not already exist")
    asset = "utility.async_stream_queue.external.dartlang.async"
    target = output / "intake" / asset / "0.1.0"
    payload = target / "payload" / "src"
    shutil.copytree(bundle, payload, symlinks=True)
    digest = payload_tree_sha256(payload)
    license_path = payload / "vendor" / "async" / "LICENSE"
    if not license_path.is_file() or license_path.is_symlink():
        raise ValueError("upstream original license missing")
    template = json.loads((root / "intake/utility.int64_arithmetic.external.dartlang.fixnum/0.1.0/manifest.json").read_text())
    manifest = copy.deepcopy(template)
    manifest.update(
        id=asset, name="Dart async StreamQueue — tested AIVEXUS adapter",
        description="Source-bound external StreamQueue adapter executed by an independent Linux Dart consumer; not certified.",
        capabilities=["utility.async_stream_queue"], platforms=["linux"],
        entry_paths=["lib/aivexus_external.dart"], status="tested")
    manifest["provenance"].update(
        source_commit=verified["source_commit"], source_tag=None,
        source_subtree=candidate["source_path"],
        source_task_id="researcher-next-external-dart:async",
        retrieved_at=datetime.now(timezone.utc).isoformat())
    manifest["payload"].update(sha256=digest, upstream_commit=verified["source_commit"])
    manifest["validation"].update(
        score=0.8, tests_passed=True, validated_on=["linux"],
        validated_at=datetime.now(timezone.utc).isoformat(),
        test_report="tests/dart-linux-ci-report.json")
    manifest["connector"]["provides"] = [{
        "capability_id": "utility.async_stream_queue",
        "contract_id": "utility.async_stream_queue.v1",
        "contract_version": "1.0"}]
    manifest["security"].update(reviewed=False, reviewed_at=None, known_vulnerabilities=None,
                                sbom=None, review_report=None,
                                notes="Independent license/security/privacy review and signature missing.")
    manifest["integration"]["adapter_notes"] = "StreamQueue only; tested on Linux Dart, not on Android or Windows."
    manifest["quality"].update(reuse_count=0, successful_integrations=0, failed_integrations=0, last_used_at=None)
    (target / "provenance").mkdir(parents=True)
    shutil.copyfile(license_path, target / "provenance" / "LICENSE")
    (target / "tests").mkdir()
    receipt = {
        "schema": "ai-orchestrator.library-test-report.v1",
        "asset_id": asset, "version": "0.1.0",
        "source_commit": verified["source_commit"], "payload_sha256": digest,
        "passed": True, "validated_on": ["linux"],
        "generated_at": manifest["validation"]["validated_at"],
        "evidence": {
            "github_run_id": int(os.environ["GITHUB_RUN_ID"]),
            "github_commit": os.environ["GITHUB_SHA"],
            "checks": ["upstream dart test", "separate consumer dart analyze and run",
                       "delivered adapter consumer dart analyze and run"],
            "delivery_bundle_sha256": delivery["bundle_sha256"],
        },
        "independent_security_reviewed": False, "certification_authorized": False,
    }
    (target / "tests/dart-linux-ci-report.json").write_text(json.dumps(receipt, indent=2) + "\n")
    (target / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (output / "README.txt").write_text(
        "TESTED-only candidate generated by CI; NOT ADMITTED OR CERTIFIED. Independent review required.\n")
    print(json.dumps({"asset_id": asset, "payload_sha256": digest,
                      "ci_run_id": receipt["evidence"]["github_run_id"],
                      "status": "TESTED_CANDIDATE_NOT_ADMITTED",
                      "certification_authorized": False}))


def main():
    p = argparse.ArgumentParser()
    for name in ("root", "candidate", "upstream", "consumer", "adapter", "delivery", "bundle", "output"):
        p.add_argument("--" + name, type=Path, required=True)
    a = p.parse_args()
    materialize(a.root, *(json.loads(getattr(a, name).read_text())
                          for name in ("candidate", "upstream", "consumer", "adapter", "delivery")),
                a.bundle, a.output)


if __name__ == "__main__":
    main()
